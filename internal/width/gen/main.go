//go:build ignore

// Command gen writes tables.go from the Unicode data files in ../data.
//
//	go run gen/main.go data/EastAsianWidth.txt data/emoji-data.txt data/emoji-zwj-sequences.txt > tables.go
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

type rng [2]int

func ranges(path string, want map[string]bool) map[string][]rng {
	f, err := os.Open(path)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()
	out := map[string][]rng{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		parts := strings.Split(line, ";")
		prop := strings.TrimSpace(parts[1])
		if !want[prop] {
			continue
		}
		lo, hi, _ := strings.Cut(strings.TrimSpace(parts[0]), "..")
		if hi == "" {
			hi = lo
		}
		a, _ := strconv.ParseInt(lo, 16, 32)
		b, _ := strconv.ParseInt(hi, 16, 32)
		out[prop] = append(out[prop], rng{int(a), int(b)})
	}
	return out
}

func merge(rs []rng) []rng {
	sort.Slice(rs, func(i, j int) bool { return rs[i][0] < rs[j][0] })
	var m []rng
	for _, r := range rs {
		if n := len(m); n > 0 && r[0] <= m[n-1][1]+1 {
			if r[1] > m[n-1][1] {
				m[n-1][1] = r[1]
			}
		} else {
			m = append(m, r)
		}
	}
	return m
}

var buf bytes.Buffer

func emit(name string, rs []rng) {
	fmt.Fprintf(&buf, "var %s = [][2]rune{\n", name)
	for _, r := range merge(rs) {
		fmt.Fprintf(&buf, "\t{0x%X, 0x%X},\n", r[0], r[1])
	}
	buf.WriteString("}\n\n")
}

// zwjSequences reads emoji-zwj-sequences.txt: each standard (RGI) ZWJ sequence
// as a string without U+FE0F, sorted. Prettier's emoji pattern matches a
// sequence with or without its variation selectors, so the table drops them.
func zwjSequences(path string) []string {
	f, err := os.Open(path)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()
	seen := map[string]bool{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		field, _, _ := strings.Cut(line, ";")
		var rs []rune
		for _, h := range strings.Fields(field) {
			n, err := strconv.ParseInt(h, 16, 32)
			if err != nil {
				fmt.Fprintln(os.Stderr, "bad code point", h)
				os.Exit(1)
			}
			if n != 0xFE0F {
				rs = append(rs, rune(n))
			}
		}
		if len(rs) > 0 {
			seen[string(rs)] = true
		}
	}
	out := make([]string, 0, len(seen))
	for s := range seen {
		out = append(out, s)
	}
	sort.Strings(out)
	return out
}

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: gen EastAsianWidth.txt emoji-data.txt emoji-zwj-sequences.txt")
		os.Exit(2)
	}
	eaw := ranges(os.Args[1], map[string]bool{"W": true, "F": true})
	emo := ranges(os.Args[2], map[string]bool{"Extended_Pictographic": true, "Emoji_Presentation": true})
	buf.WriteString("// Code generated by gen/main.go from Unicode 17.0.0 EastAsianWidth.txt, emoji-data.txt and emoji-zwj-sequences.txt. DO NOT EDIT.\n\npackage width\n\n")
	emit("wideRanges", append(eaw["W"], eaw["F"]...))
	emit("pictoRanges", emo["Extended_Pictographic"])
	emit("emojiPresRanges", emo["Emoji_Presentation"])
	buf.WriteString("// zwjSequences holds each standard emoji ZWJ sequence without U+FE0F.\nvar zwjSequences = map[string]bool{\n")
	for _, s := range zwjSequences(os.Args[3]) {
		fmt.Fprintf(&buf, "\t%s: true,\n", strconv.QuoteToASCII(s))
	}
	buf.WriteString("}\n")
	src, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	os.Stdout.Write(src)
}
