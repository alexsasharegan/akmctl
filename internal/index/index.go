// Package index generates README.md in the ADR folder, the routing table of ADRs, in the
// form Prettier leaves unchanged.
package index

import (
	"path"
	"sort"
	"strings"

	"github.com/alexsasharegan/akmctl/internal/record"
	"github.com/alexsasharegan/akmctl/internal/width"
)

const header = "<!-- generated by akmctl index; do not edit -->\n"

var groups = []struct {
	title    string
	statuses []string
}{
	{"In force", []string{"accepted"}},
	{"Proposed", []string{"proposed"}},
	{"Not in force", []string{"rejected", "deprecated", "superseded"}},
}

var columns = []string{"id", "title", "date", "scope", "summary", "supersedes / superseded_by"}

// Generate returns the text of the index for the ADRs of repo.
func Generate(repo *record.Repo) string {
	var adrs []*record.Record
	for _, r := range repo.Records {
		if r.Type == record.ADR {
			adrs = append(adrs, r)
		}
	}
	sort.SliceStable(adrs, func(i, j int) bool { return adrs[i].ID < adrs[j].ID })
	var b strings.Builder
	b.WriteString(header)
	for _, g := range groups {
		rows := [][]string{columns}
		for _, r := range adrs {
			if contains(g.statuses, r.Status()) {
				rows = append(rows, row(r))
			}
		}
		if len(rows) == 1 {
			continue
		}
		b.WriteString("\n## " + g.title + "\n\n")
		b.WriteString(table(rows))
	}
	return b.String()
}

func row(r *record.Record) []string {
	var links []string
	for _, k := range []string{"supersedes", "superseded_by"} {
		if v := record.RefID(r.Str(k)); v != "" {
			links = append(links, v)
		}
	}
	return []string{
		"[" + r.ID + "](" + path.Base(r.Path) + ")",
		cell(r.Str("title")),
		cell(r.Str("date")),
		cell(strings.Join(r.Fields["scope"].Strings(), ", ")),
		cell(r.Str("summary")),
		strings.Join(links, " / "),
	}
}

// cell makes text safe for a table cell: whitespace runs collapse to one space
// (Prettier does the same) and a pipe is escaped.
func cell(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.ReplaceAll(s, "|", `\|`)
}

func table(rows [][]string) string {
	w := make([]int, len(rows[0]))
	for _, r := range rows {
		for i, c := range r {
			if n := width.String(c); n > w[i] {
				w[i] = n
			}
		}
	}
	for i := range w {
		if w[i] < 3 {
			w[i] = 3
		}
	}
	var b strings.Builder
	line := func(r []string) {
		b.WriteString("|")
		for i, c := range r {
			b.WriteString(" " + c + strings.Repeat(" ", w[i]-width.String(c)) + " |")
		}
		b.WriteString("\n")
	}
	line(rows[0])
	sep := make([]string, len(w))
	for i := range sep {
		sep[i] = strings.Repeat("-", w[i])
	}
	line(sep)
	for _, r := range rows[1:] {
		line(r)
	}
	return b.String()
}

func contains(l []string, s string) bool {
	for _, x := range l {
		if x == s {
			return true
		}
	}
	return false
}
